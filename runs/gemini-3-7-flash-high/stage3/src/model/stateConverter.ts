import { HardwareState } from './hardware';
import { ProgramData } from './programs';

export function hardwareStateToProgramData(
  state: HardwareState,
  id: string | number,
  name: string,
  category: string = 'User'
): ProgramData {
  const strId = typeof id === 'number'
    ? `${Math.floor((id - 1) / 8) + 1}.${((id - 1) % 8) + 1}`
    : id;

  return {
    id: strId,
    name,
    category,
    tempoBpm: state.tempo_bpm,
    transpose: state.transpose,
    splits: {
      enabled: state.split,
      lowSplitActive: state.split_low_active,
      lowPosition: state.split_low_pos,
      lowCrossfade: state.split_low_xfade,
      midSplitActive: state.split_mid_active,
      midPosition: state.split_mid_pos,
      midCrossfade: state.split_mid_xfade,
      highSplitActive: state.split_high_active,
      highPosition: state.split_high_pos,
      highCrossfade: state.split_high_xfade,
    },
    layerZones: {
      pianoA: { ...state.piano_layer_a_zones },
      pianoB: { ...state.piano_layer_b_zones },
      organA: { ...state.organ_layer_a_zones },
      organB: { ...state.organ_layer_b_zones },
      synthA: { ...state.synth_layer_a_zones },
      synthB: { ...state.synth_layer_b_zones },
      synthC: { ...state.synth_layer_c_zones },
    },
    layerScenes: {
      activeScene: state.layer_scene,
      scene1: {
        pianoA: state.piano_layer_a_on,
        pianoB: state.piano_layer_b_on,
        organA: state.organ_layer_a_on,
        organB: state.organ_layer_b_on,
        synthA: state.synth_layer_a_on,
        synthB: state.synth_layer_b_on,
        synthC: state.synth_layer_c_on,
      },
      scene2: {
        pianoA: state.piano_layer_a_on,
        pianoB: state.piano_layer_b_on,
        organA: state.organ_layer_a_on,
        organB: state.organ_layer_b_on,
        synthA: state.synth_layer_a_on,
        synthB: state.synth_layer_b_on,
        synthC: state.synth_layer_c_on,
      },
    },
    morphAssignments: [...state.morph_assignments],

    piano: {
      on: state.piano_on,
      type: state.piano_type,
      model: state.piano_model,
      kbTouch: state.piano_kb_touch,
      timbre: state.piano_timbre,
      dynComp: state.piano_dyn_comp,
      unison: state.piano_unison,
      softRelease: state.piano_soft_release,
      stringRes: state.piano_string_res,
      sustain: state.piano_sustain,
      pstick: state.piano_pstick,
      layerA: {
        on: state.piano_layer_a_on,
        level: state.piano_layer_a_level,
        octave: state.piano_layer_a_octave,
      },
      layerB: {
        on: state.piano_layer_b_on,
        level: state.piano_layer_b_level,
        octave: state.piano_layer_b_octave,
      },
    },

    organ: {
      on: state.organ_on,
      model: state.organ_model,
      drawbars: [
        state.organ_db_16,
        state.organ_db_5_1_3,
        state.organ_db_8,
        state.organ_db_4,
        state.organ_db_2_2_3,
        state.organ_db_2,
        state.organ_db_1_3_5,
        state.organ_db_1_1_3,
        state.organ_db_1,
      ],
      percussionOn: state.organ_percussion_on,
      percussionSoft: state.organ_percussion_soft,
      percussionFast: state.organ_percussion_fast,
      percussionThird: state.organ_percussion_third,
      vibratoOn: state.organ_vibrato_on,
      vibratoMode: state.organ_vibrato_mode,
      rotaryStop: state.organ_rotary_stop,
      rotarySpeed: state.organ_rotary_speed,
      sustain: state.organ_sustain,
      pstick: state.organ_pstick,
      layerA: {
        on: state.organ_layer_a_on,
        level: state.organ_layer_a_level,
        octave: state.organ_layer_a_octave,
        vibratoOn: state.organ_layer_a_vibrato,
      },
      layerB: {
        on: state.organ_layer_b_on,
        level: state.organ_layer_b_level,
        octave: state.organ_layer_b_octave,
        vibratoOn: state.organ_layer_b_vibrato,
      },
    },

    synth: {
      on: state.synth_on,
      oscCategory: state.synth_osc_category,
      waveform: state.synth_waveform,
      oscMod: state.synth_osc_mod,
      filterType: state.synth_filter_type,
      filterCutoff: state.synth_filter_cutoff,
      filterResonance: state.synth_filter_resonance,
      filterDrive: state.synth_filter_drive,
      filterEnvAmt: state.synth_filter_env_amt,
      filterKbTracking: state.synth_filter_kb_tracking,
      ampAttack: state.synth_amp_attack,
      ampDecay: state.synth_amp_decay,
      ampSustain: state.synth_amp_sustain,
      ampRelease: state.synth_amp_release,
      ampVelocity: state.synth_amp_velocity,
      modAttack: state.synth_mod_attack,
      modDecay: state.synth_mod_decay,
      modRelease: state.synth_mod_release,
      modVelocity: state.synth_mod_velocity,
      modToPitch: state.synth_mod_to_pitch,
      modEnvAmt: state.synth_mod_env_amt,
      lfoWaveform: state.synth_lfo_waveform,
      lfoDestination: state.synth_lfo_destination,
      lfoRate: state.synth_lfo_rate,
      lfoAmount: state.synth_lfo_amount,
      lfoClockSync: state.synth_lfo_clock_sync,
      voiceMode: state.synth_voice_mode,
      voicePriority: state.synth_voice_priority,
      glide: state.synth_glide,
      unison: state.synth_unison_level,
      vibratoMode: state.synth_vibrato_mode,
      vibratoRate: state.synth_vibrato_rate,
      vibratoAmount: state.synth_vibrato_amount,
      arpMode: state.synth_arp_mode,
      arpDirection: state.synth_arp_direction,
      arpRange: state.synth_arp_range,
      arpRate: state.synth_arp_rate,
      arpClockSync: state.synth_arp_clock_sync,
      arpKbHold: state.synth_arp_kb_hold,
      arpRun: state.synth_arp_run,
      sustain: state.synth_sustain,
      pstick: state.synth_pstick,
      pitchCoarse: state.synth_pitch_coarse,
      pitchFine: state.synth_pitch_fine,
      layerA: {
        on: state.synth_layer_a_on,
        level: state.synth_layer_a_level,
        octave: state.synth_layer_a_octave,
      },
      layerB: {
        on: state.synth_layer_b_on,
        level: state.synth_layer_b_level,
        octave: state.synth_layer_b_octave,
      },
      layerC: {
        on: state.synth_layer_c_on,
        level: state.synth_layer_c_level,
        octave: state.synth_layer_c_octave,
      },
    },

    effects: {
      allEffectsOn: state.layer_effects_on,
      effect1: {
        on: state.effect_1_on,
        type: state.effect_1_type,
        rate: state.effect_1_rate,
        amount: state.effect_1_amount,
        clockSync: state.effect_1_clock_sync,
      },
      effect2: {
        on: state.effect_2_on,
        type: state.effect_2_type,
        rate: state.effect_2_rate,
        amount: state.effect_2_amount,
      },
      delay: {
        on: state.delay_on,
        tempo: state.delay_tempo,
        feedback: state.delay_feedback,
        amount: state.delay_amount,
        pingpong: state.delay_pingpong,
        filter: state.delay_filter,
        global: state.delay_global,
        clockSync: state.delay_clock_sync,
      },
      ampEq: {
        on: state.amp_eq_on,
        type: state.amp_type,
        drive: state.amp_drive,
        bass: state.eq_bass,
        mid: state.eq_mid,
        midFreq: state.eq_mid_freq,
        treble: state.eq_treble,
      },
      compressor: {
        on: state.compressor_on,
        amount: state.compressor_amount,
        fast: state.compressor_fast,
        global: state.compressor_global,
      },
      reverb: {
        on: state.reverb_on,
        type: state.reverb_type,
        decay: state.reverb_decay,
        amount: state.reverb_amount,
        bright: state.reverb_bright,
        global: state.reverb_global,
      },
      rotary: {
        on: state.rotary_on,
        speed: state.rotary_speed,
        stop: state.rotary_stop,
        drive: state.rotary_drive,
        organRouted: state.rotary_organ_routed,
      },
      groupPiano: state.effects_group_piano,
      groupSynth: state.effects_group_synth,
    },
  };
}

export function applyProgramDataToHardwareState(
  prog: ProgramData,
  currentState: HardwareState
): HardwareState {
  // Respect master_level from currentState (as Master Level is not stored in programs per spec)
  const isScene2 = prog.layerScenes?.activeScene === 2;
  const activeSceneLayers = isScene2 ? prog.layerScenes.scene2 : prog.layerScenes.scene1;

  return {
    ...currentState,
    tempo_bpm: prog.tempoBpm ?? 120,
    transpose: prog.transpose ?? 0,
    transpose_active: (prog.transpose ?? 0) !== 0,
    is_dirty: false,
    layer_scene: prog.layerScenes?.activeScene ?? 1,

    // Splits
    split: prog.splits?.enabled ?? false,
    split_low_active: prog.splits?.lowSplitActive ?? false,
    split_low_pos: prog.splits?.lowPosition ?? 'C3',
    split_low_xfade: prog.splits?.lowCrossfade ?? 0,
    split_mid_active: prog.splits?.midSplitActive ?? true,
    split_mid_pos: prog.splits?.midPosition ?? 'C4',
    split_mid_xfade: prog.splits?.midCrossfade ?? 0,
    split_high_active: prog.splits?.highSplitActive ?? false,
    split_high_pos: prog.splits?.highPosition ?? 'C5',
    split_high_xfade: prog.splits?.highCrossfade ?? 0,

    // Zones
    piano_layer_a_zones: prog.layerZones?.pianoA ?? { ...currentState.piano_layer_a_zones },
    piano_layer_b_zones: prog.layerZones?.pianoB ?? { ...currentState.piano_layer_b_zones },
    organ_layer_a_zones: prog.layerZones?.organA ?? { ...currentState.organ_layer_a_zones },
    organ_layer_b_zones: prog.layerZones?.organB ?? { ...currentState.organ_layer_b_zones },
    synth_layer_a_zones: prog.layerZones?.synthA ?? { ...currentState.synth_layer_a_zones },
    synth_layer_b_zones: prog.layerZones?.synthB ?? { ...currentState.synth_layer_b_zones },
    synth_layer_c_zones: prog.layerZones?.synthC ?? { ...currentState.synth_layer_c_zones },

    // Morphs
    morph_assignments: prog.morphAssignments ? [...prog.morphAssignments] : [],

    // Piano
    piano_on: prog.piano.on,
    piano_type: prog.piano.type,
    piano_model: prog.piano.model,
    piano_kb_touch: prog.piano.kbTouch,
    piano_timbre: prog.piano.timbre,
    piano_dyn_comp: prog.piano.dynComp,
    piano_unison: prog.piano.unison,
    piano_soft_release: prog.piano.softRelease,
    piano_string_res: prog.piano.stringRes,
    piano_sustain: prog.piano.sustain,
    piano_pstick: prog.piano.pstick,
    piano_layer_a_on: activeSceneLayers?.pianoA ?? prog.piano.layerA.on,
    piano_layer_a_level: prog.piano.layerA.level,
    piano_layer_a_octave: prog.piano.layerA.octave,
    piano_layer_b_on: activeSceneLayers?.pianoB ?? prog.piano.layerB.on,
    piano_layer_b_level: prog.piano.layerB.level,
    piano_layer_b_octave: prog.piano.layerB.octave,

    // Organ
    organ_on: prog.organ.on,
    organ_model: prog.organ.model,
    organ_db_16: prog.organ.drawbars[0],
    organ_db_5_1_3: prog.organ.drawbars[1],
    organ_db_8: prog.organ.drawbars[2],
    organ_db_4: prog.organ.drawbars[3],
    organ_db_2_2_3: prog.organ.drawbars[4],
    organ_db_2: prog.organ.drawbars[5],
    organ_db_1_3_5: prog.organ.drawbars[6],
    organ_db_1_1_3: prog.organ.drawbars[7],
    organ_db_1: prog.organ.drawbars[8],
    organ_percussion_on: prog.organ.percussionOn,
    organ_percussion_soft: prog.organ.percussionSoft,
    organ_percussion_fast: prog.organ.percussionFast,
    organ_percussion_third: prog.organ.percussionThird,
    organ_vibrato_on: prog.organ.vibratoOn,
    organ_vibrato_mode: prog.organ.vibratoMode,
    organ_rotary_stop: prog.organ.rotaryStop,
    organ_rotary_speed: prog.organ.rotarySpeed,
    organ_sustain: prog.organ.sustain,
    organ_pstick: prog.organ.pstick,
    organ_layer_a_on: activeSceneLayers?.organA ?? prog.organ.layerA.on,
    organ_layer_a_level: prog.organ.layerA.level,
    organ_layer_a_octave: prog.organ.layerA.octave,
    organ_layer_a_vibrato: prog.organ.layerA.vibratoOn,
    organ_layer_b_on: activeSceneLayers?.organB ?? prog.organ.layerB.on,
    organ_layer_b_level: prog.organ.layerB.level,
    organ_layer_b_octave: prog.organ.layerB.octave,
    organ_layer_b_vibrato: prog.organ.layerB.vibratoOn,

    // Synth
    synth_on: prog.synth.on,
    synth_osc_category: prog.synth.oscCategory,
    synth_osc_type: prog.synth.oscCategory,
    synth_waveform: prog.synth.waveform,
    synth_osc_mod: prog.synth.oscMod,
    synth_filter_type: prog.synth.filterType,
    synth_filter_cutoff: prog.synth.filterCutoff,
    synth_filter_resonance: prog.synth.filterResonance,
    synth_filter_drive: prog.synth.filterDrive,
    synth_filter_env_amt: prog.synth.filterEnvAmt,
    synth_filter_kb_tracking: prog.synth.filterKbTracking,
    synth_amp_attack: prog.synth.ampAttack,
    synth_amp_decay: prog.synth.ampDecay,
    synth_amp_sustain: prog.synth.ampSustain,
    synth_amp_release: prog.synth.ampRelease,
    synth_amp_velocity: prog.synth.ampVelocity,
    synth_mod_attack: prog.synth.modAttack,
    synth_mod_decay: prog.synth.modDecay,
    synth_mod_release: prog.synth.modRelease,
    synth_mod_velocity: prog.synth.modVelocity,
    synth_mod_to_pitch: prog.synth.modToPitch,
    synth_mod_env_amt: prog.synth.modEnvAmt,
    synth_lfo_waveform: prog.synth.lfoWaveform,
    synth_lfo_destination: prog.synth.lfoDestination,
    synth_lfo_rate: prog.synth.lfoRate,
    synth_lfo_amount: prog.synth.lfoAmount,
    synth_lfo_clock_sync: prog.synth.lfoClockSync,
    synth_voice_mode: prog.synth.voiceMode,
    synth_voice_priority: prog.synth.voicePriority,
    synth_glide: prog.synth.glide,
    synth_unison: prog.synth.unison > 0,
    synth_unison_level: prog.synth.unison,
    synth_vibrato: prog.synth.vibratoMode > 0,
    synth_vibrato_mode: prog.synth.vibratoMode,
    synth_vibrato_rate: prog.synth.vibratoRate,
    synth_vibrato_amount: prog.synth.vibratoAmount,
    synth_arp_mode: prog.synth.arpMode,
    synth_arp_direction: prog.synth.arpDirection,
    synth_arp_range: prog.synth.arpRange,
    synth_arp_rate: prog.synth.arpRate,
    synth_arp_clock_sync: prog.synth.arpClockSync,
    synth_arp_kb_hold: prog.synth.arpKbHold,
    synth_arp_run: prog.synth.arpRun,
    synth_sustain: prog.synth.sustain,
    synth_pstick: prog.synth.pstick,
    synth_pitch_coarse: prog.synth.pitchCoarse,
    synth_pitch_fine: prog.synth.pitchFine,
    synth_layer_a_on: activeSceneLayers?.synthA ?? prog.synth.layerA.on,
    synth_layer_a_level: prog.synth.layerA.level,
    synth_layer_a_octave: prog.synth.layerA.octave,
    synth_layer_b_on: activeSceneLayers?.synthB ?? prog.synth.layerB.on,
    synth_layer_b_level: prog.synth.layerB.level,
    synth_layer_b_octave: prog.synth.layerB.octave,
    synth_layer_c_on: activeSceneLayers?.synthC ?? prog.synth.layerC.on,
    synth_layer_c_level: prog.synth.layerC.level,
    synth_layer_c_octave: prog.synth.layerC.octave,

    // Effects
    layer_effects_on: prog.effects.allEffectsOn,
    effect_1_on: prog.effects.effect1.on,
    effect_1_type: prog.effects.effect1.type,
    effect_1_rate: prog.effects.effect1.rate,
    effect_1_amount: prog.effects.effect1.amount,
    effect_1_clock_sync: prog.effects.effect1.clockSync,
    effect_2_on: prog.effects.effect2.on,
    effect_2_type: prog.effects.effect2.type,
    effect_2_rate: prog.effects.effect2.rate,
    effect_2_amount: prog.effects.effect2.amount,
    delay_on: prog.effects.delay.on,
    delay_tempo: prog.effects.delay.tempo,
    delay_feedback: prog.effects.delay.feedback,
    delay_amount: prog.effects.delay.amount,
    delay_pingpong: prog.effects.delay.pingpong,
    delay_filter: prog.effects.delay.filter,
    delay_global: prog.effects.delay.global,
    delay_clock_sync: prog.effects.delay.clockSync,
    amp_eq_on: prog.effects.ampEq.on,
    amp_type: prog.effects.ampEq.type,
    amp_drive: prog.effects.ampEq.drive,
    eq_bass: prog.effects.ampEq.bass,
    eq_mid: prog.effects.ampEq.mid,
    eq_mid_freq: prog.effects.ampEq.midFreq,
    eq_treble: prog.effects.ampEq.treble,
    compressor_on: prog.effects.compressor.on,
    compressor_amount: prog.effects.compressor.amount,
    compressor_fast: prog.effects.compressor.fast,
    compressor_global: prog.effects.compressor.global,
    reverb_on: prog.effects.reverb.on,
    reverb_type: prog.effects.reverb.type,
    reverb_decay: prog.effects.reverb.decay,
    reverb_amount: prog.effects.reverb.amount,
    reverb_bright: prog.effects.reverb.bright,
    reverb_global: prog.effects.reverb.global,
    rotary_on: prog.effects.rotary.on,
    rotary_speed: prog.effects.rotary.speed,
    rotary_stop: prog.effects.rotary.stop,
    rotary_drive: prog.effects.rotary.drive,
    rotary_organ_routed: prog.effects.rotary.organRouted,
    effects_group_piano: prog.effects.groupPiano,
    effects_group_synth: prog.effects.groupSynth,
  };
}
